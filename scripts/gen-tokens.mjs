// Generates web/src/cyac/tokens.css from the vendored CyAc tokens.json.
// Void is the default theme on :root; Paper applies under [data-theme="paper"].
import { readFileSync, writeFileSync } from "node:fs";

const src = new URL("../web/src/cyac/tokens.json", import.meta.url);
const out = new URL("../web/src/cyac/tokens.css", import.meta.url);
const t = JSON.parse(readFileSync(src, "utf8"));

const ref = (v) => (typeof v === "string" ? v.replace(/\{([a-z0-9-]+)\}/g, "var(--$1)") : v);
const voidVars = [];
const paperVars = [];
for (const tok of t.color.tokens) {
  if (typeof tok.value === "string") {
    voidVars.push(`  --${tok.name}: ${ref(tok.value)};`);
  } else {
    voidVars.push(`  --${tok.name}: ${ref(tok.value.void)};`);
    paperVars.push(`  --${tok.name}: ${ref(tok.value.paper)};`);
  }
}
const shared = [];
for (const [k, v] of Object.entries(t.type.families)) shared.push(`  --font-${k}: ${v};`);
for (const group of ["spacing", "radius", "stroke"]) {
  for (const tok of t[group].tokens) shared.push(`  --${tok.name}: ${tok.value};`);
}

const css = `/* Generated by scripts/gen-tokens.mjs from tokens.json. Do not edit by hand. */
@font-face {
  font-family: "ModeNine";
  src: url("/fonts/ModeNine.ttf") format("truetype");
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}

:root {
  color-scheme: dark;
${shared.join("\n")}
${voidVars.join("\n")}
}

[data-theme="paper"] {
  color-scheme: light;
${paperVars.join("\n")}
}
`;
writeFileSync(out, css);
console.log(`wrote ${out.pathname}`);
